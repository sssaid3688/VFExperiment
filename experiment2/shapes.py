def attn_flops_bytes(B, Sq, Skv, Hq, Hkv, D, causal=True):
    """FLOPs 模型: 2 次 GEMM (QK^T 与 PV), 每个 MAC 2 flops
    causal(bottom-right) 实际对齐 pair 数 = Sq*(Skv-Sq) + Sq*(Sq+1)/2"""
    if causal:
        pairs = Sq * (Skv - Sq) + Sq * (Sq + 1) // 2
    else:
        pairs = Sq * Skv
    flops = 4 * B * Hq * D * pairs
    bytes_ = 2 * (B * Sq * Hq * D + 2 * B * Skv * Hkv * D + B * Sq * Hq * D)
    return flops, bytes_


